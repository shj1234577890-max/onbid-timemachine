/** 지역 열쇠: 시·도와 시·군·구를 "|"로 잇는다. (예: "대구|수성구") 지역별 사례 수를 셀 때 쓴다. */
export function regionKey(sido: Sido, sigungu: string): string {
  return `${sido}|${sigungu}`;
}

